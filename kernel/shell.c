// ─────────────────────────────────────────────────
// shell_run: main shell loop (never returns)
// ─────────────────────────────────────────────────
void shell_run() {
    static char input[MAX_INPUT];
    static int  input_len = 0;
    static int  hist_nav  = -1;

    while (1) {
        __asm__ volatile("hlt");

        while (keyboard_has_input()) {
            char c = keyboard_getchar();

            // ── Arrow keys ──
            if (c == KEY_UP) {
                if (history_count == 0) continue;
                if (hist_nav == -1)
                    hist_nav = history_count - 1;
                else if (hist_nav > 0)
                    hist_nav--;

                // Clear current line
                for (int i = 0; i < input_len; i++) {
                    print_char('\b');
                }
                kstrcpy(input, history[hist_nav % HISTORY_SIZE]);
                input_len = kstrlen(input);
                print(input);
                continue;
            }

            if (c == KEY_DOWN) {
                if (hist_nav == -1) continue;
                hist_nav++;
                for (int i = 0; i < input_len; i++) {
                    print_char('\b');
                }
                if (hist_nav >= history_count) {
                    hist_nav = -1;
                    input[0] = '\0';
                    input_len = 0;
                } else {
                    kstrcpy(input, history[hist_nav % HISTORY_SIZE]);
                    input_len = kstrlen(input);
                    print(input);
                }
                continue;
            }

            // ── Backspace ──
            if (c == KEY_BACKSPACE) {
                if (input_len > 0) {
                    input_len--;
                    print_char('\b');
                    print_char(' ');
                    print_char('\b');
                }
                continue;
            }

            // ── Enter ──
            if (c == '\n') {
                print_char('\n');
                input[input_len] = '\0';
                history_push(input);
                hist_nav  = -1;
                dispatch(input);
                input_len = 0;
                input[0]  = '\0';
                print_prompt();
                continue;
            }

            // ── Printable character ──
            if (c >= ' ' && c < 127 && input_len < MAX_INPUT - 1) {
                input[input_len++] = c;
                print_char(c);
            }
        }
    }
}
