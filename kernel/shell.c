static int parse_int_safe(const char* s, int* out) {
    int v = 0; int any = 0;
    for (const char* p = s; *p; p++) {
        if (*p < '0' || *p > '9') return 0;
        v = v * 10 + (*p - '0');
        any = 1;
    }
    if (!any) return 0;
    *out = v; return 1;
}

static void cmd_tcpconnect() {
    if (argc < 3) {
        print_color("\n  Usage: tcpconnect <a.b.c.d> <port>\n\n",
                    MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    uint8_t ip[4];
    int port_int;
    if (!parse_ipv4(argv[1], ip) || !parse_int_safe(argv[2], &port_int) ||
        port_int <= 0 || port_int > 65535) {
        print_color("\n  Bad ip or port\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    print_color("\n  TCP connect ", YELLOW_ON_BLACK);
    print_ip(ip); print_char(':'); print_int(port_int); print_char('\n');
    int id = tcp_connect(ip, (uint16_t)port_int);
    if (id < 0) {
        print_color("  tcp_connect failed (no free TCB)\n\n",
                    MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    // Drive the pump until we leave SYN_SENT or time out.
    for (int i = 0; i < 80; i++) {
        net_pump_run(100);
        int s = tcp_state(id);
        if (s != TCP_SYN_SENT) break;
    }
    int s = tcp_state(id);
    print("  Result: "); print(tcp_state_name(s));
    if (s == TCP_ESTABLISHED) {
        print_color("  (handshake OK)\n", MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
        tcp_close(id);
        net_pump_run(500);
    } else {
        print_color("  (no connection)\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
    }
    print_char('\n');
}

static uint16_t mini_strlen(const char* s) {
    uint16_t n = 0; while (s[n]) n++; return n;
}

static void cmd_tcpsend() {
    if (argc < 3) {
        print_color("\n  Usage: tcpsend <conn_id> <text>\n\n",
                    MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    int id;
    if (!parse_int_safe(argv[1], &id)) {
        print_color("\n  Bad id\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    uint16_t total = 0;
    for (int i = 2; i < argc; i++) {
        uint16_t n = mini_strlen(argv[i]);
        int sent = tcp_send(id, (const uint8_t*)argv[i], n);
        if (sent < 0) {
            print_color("\n  tcp_send: not ESTABLISHED or bad id\n\n",
                        MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
            return;
        }
        total += (uint16_t)sent;
        if (i + 1 < argc) {
            uint8_t sp = ' ';
            int s2 = tcp_send(id, &sp, 1);
            if (s2 > 0) total++;
        }
    }
    uint8_t nl = '\n';
    tcp_send(id, &nl, 1);
    print_color("\n  Sent ", MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
    print_int(total + 1); print(" bytes\n\n");
}

static void cmd_tcprecv() {
    if (argc < 2) {
        print_color("\n  Usage: tcprecv <conn_id> [wait_ms]\n\n",
                    MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    int id, wait_ms = 1000;
    if (!parse_int_safe(argv[1], &id)) {
        print_color("\n  Bad id\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    if (argc >= 3) parse_int_safe(argv[2], &wait_ms);

    static uint8_t buf[1024];
    int total = 0;
    int slices = wait_ms / 100;
    if (slices < 1) slices = 1;
    for (int s = 0; s < slices; s++) {
        net_pump_run(100);
        int n = tcp_recv(id, buf, sizeof(buf) - 1);
        if (n < 0) {
            print_color("\n  tcp_recv: bad id\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
            return;
        }
        if (n > 0) {
            buf[n] = 0;
            for (int i = 0; i < n; i++) print_char((char)buf[i]);
            total += n;
        }
    }
    if (total == 0) print_color("\n  (no data)\n\n", MAKE_COLOR(COLOR_DARK_GREY, COLOR_BLACK));
    else            { print_color("\n  -- ", MAKE_COLOR(COLOR_DARK_GREY, COLOR_BLACK));
                      print_int(total); print(" bytes received --\n\n"); }
}

