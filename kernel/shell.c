// ─────────────────────────────────────────────────
// Userland-style syscall wrappers — invoke int 0x80
// (exactly how a user program would call the kernel)
// ─────────────────────────────────────────────────
static uint64_t do_syscall(uint64_t num, uint64_t arg1) {
    uint64_t ret;
    __asm__ volatile("int $0x80"
                     : "=a"(ret)
                     : "a"(num), "D"(arg1)
                     : "memory");
    return ret;
}

