static void cmd_peek() {
    if (argc < 2) {
        print_color("\n  Usage: peek <hexaddr>   e.g. peek b8000\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    // Parse hex address
    uint64_t addr = 0;
    const char* p = argv[1];
    if (p[0] == '0' && (p[1] == 'x' || p[1] == 'X')) p += 2;
    while (*p) {
        char c = *p++;
        uint8_t v;
        if (c >= '0' && c <= '9') v = c - '0';
        else if (c >= 'a' && c <= 'f') v = c - 'a' + 10;
        else if (c >= 'A' && c <= 'F') v = c - 'A' + 10;
        else break;
        addr = (addr << 4) | v;
    }

    volatile uint8_t* mem = (volatile uint8_t*) addr;
    print("\n  Memory at ");
    print_hex(addr);
    print(":\n");
    for (int row = 0; row < 4; row++) {
        print("  ");
        print_hex(addr + row * 16);
        print("  ");
        for (int col = 0; col < 16; col++) {
            uint8_t b = mem[row * 16 + col];
            const char* h = "0123456789ABCDEF";
            print_char(h[b >> 4]); print_char(h[b & 0xF]); print_char(' ');
        }
        print_char('\n');
    }
    print_char('\n');
}

