// Build an ICMP echo request, run it through the stack (loopback),
// verify the checksum — demonstrates the protocol layers working.
static void cmd_ping() {
    print_color("\n  Building ICMP echo packet (loopback)...\n\n", YELLOW_ON_BLACK);

    static uint8_t packet[64];
    for (int i = 0; i < 64; i++) packet[i] = 0;

    // Ethernet header
    eth_header_t* eth = (eth_header_t*) packet;
    for (int i = 0; i < 6; i++) { eth->dst[i] = 0xFF; eth->src[i] = net_mac()[i]; }
    eth->ethertype = htons(ETHERTYPE_IPV4);

    // IPv4 header
    ipv4_header_t* ip = (ipv4_header_t*)(packet + sizeof(eth_header_t));
    ip->ver_ihl   = 0x45;        // version 4, IHL 5
    ip->total_len = htons(sizeof(ipv4_header_t) + sizeof(icmp_header_t));
    ip->ttl       = 64;
    ip->protocol  = IP_PROTO_ICMP;
    for (int i = 0; i < 4; i++) { ip->src[i] = net_ip()[i]; ip->dst[i] = net_ip()[i]; }
    ip->checksum  = 0;
    ip->checksum  = htons(net_checksum(ip, sizeof(ipv4_header_t)));

    // ICMP header
    icmp_header_t* icmp = (icmp_header_t*)((uint8_t*)ip + sizeof(ipv4_header_t));
    icmp->type     = ICMP_ECHO_REQUEST;
    icmp->code     = 0;
    icmp->id       = htons(1);
    icmp->seq      = htons(1);
    icmp->checksum = 0;
    icmp->checksum = htons(net_checksum(icmp, sizeof(icmp_header_t)));

    print("  Ethernet : dst=ff:ff:ff:ff:ff:ff  type=IPv4\n");
    print("  IPv4     : src=");
    for (int i=0;i<4;i++){ print_int(ip->src[i]); if(i<3) print_char('.'); }
    print(" proto=ICMP  csum=");
    print_hex(ntohs(ip->checksum));
    print_char('\n');
    print("  ICMP     : type=8 (echo request)  csum=");
    print_hex(ntohs(icmp->checksum));
    print_char('\n');

    // Verify: recomputing checksum over header+checksum should yield 0
    uint16_t verify = net_checksum(ip, sizeof(ipv4_header_t));
    print("\n  IPv4 checksum verify: ");
    if (verify == 0)
        print_color("VALID (0x0000)\n", MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
    else
        print_color("INVALID\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));

    print_color("\n  Packet built & validated through the stack.\n\n",
                MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
}

static void cmd_exec() {
    const unsigned char* elf = user_init_elf;
    unsigned int elf_len = user_init_elf_len;
    const char* name = "init";
    if (argc >= 2 && kstrcmp(argv[1], "hello") == 0) {
        elf = user_hello_elf;
        elf_len = user_hello_elf_len;
        name = "hello";
    }
    print_color("\n  Loading ELF64 binary '", YELLOW_ON_BLACK);
    print(name); print("'...\n");

    uint64_t entry = elf_load(elf, elf_len);
    if (!entry) {
        print_color("  exec: not a valid ELF64 binary\n\n",
                    MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }

    print("  Entry point: ");
    print_hex(entry);
    print("\n\n");

    // Run the loaded program in ring 3
    uint64_t stack_top = (uint64_t)(user_stack + sizeof(user_stack));
    enter_user_mode(entry, stack_top);

    print_color("\n  Program exited. Back in kernel.\n\n",
                MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
}

