#define NUM_COMMANDS (sizeof(commands) / sizeof(commands[0]))

static void dispatch(const char* input) {
    if (input[0] == '\0') return;

    parse_args(input);
    if (argc == 0) return;

    for (uint32_t i = 0; i < NUM_COMMANDS; i++) {
        if (kstrcmp(argv[0], commands[i].name) == 0) {
            commands[i].handler();
            return;
        }
    }
    cmd_not_found(argv[0]);
}

