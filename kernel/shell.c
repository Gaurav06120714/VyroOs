static void cmd_diskwrite() {
    if (argc < 3) {
        print_color("\n  Usage: diskwrite <lba> <text>\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
        return;
    }
    uint32_t lba = parse_uint(argv[1]);

    static uint8_t sector[512];
    for (int i = 0; i < 512; i++) sector[i] = 0;

    // Join argv[2..] into the sector buffer
    int pos = 0;
    for (int i = 2; i < argc && pos < 510; i++) {
        const char* w = argv[i];
        for (int j = 0; w[j] && pos < 510; j++) sector[pos++] = (uint8_t)w[j];
        if (i < argc - 1 && pos < 510) sector[pos++] = ' ';
    }

    if (ata_write_sector(lba, sector) == 0) {
        print("\n  Wrote ");
        print_int(pos);
        print(" bytes to LBA ");
        print_int(lba);
        print_color("  [persisted to disk]\n\n", MAKE_COLOR(COLOR_LIGHT_GREEN, COLOR_BLACK));
    } else {
        print_color("\n  diskwrite: write failed\n\n", MAKE_COLOR(COLOR_LIGHT_RED, COLOR_BLACK));
    }
}

