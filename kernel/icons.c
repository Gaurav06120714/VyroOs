void icon_draw(const icon_t* ic, uint32_t x, uint32_t y, uint32_t size) {
    if (!ic) return;
    uint32_t step = size / 16;
    if (step == 0) step = 1;
    for (int row = 0; row < 16; row++) {
        uint16_t bits = ((uint16_t)ic->bitmap[row*2] << 8) | ic->bitmap[row*2+1];
        for (int col = 0; col < 16; col++) {
            if (bits & (0x8000 >> col)) {
                for (uint32_t dy = 0; dy < step; dy++)
                    for (uint32_t dx = 0; dx < step; dx++)
                        comp_pixel(x + col*step + dx, y + row*step + dy, ic->color);
            }
        }
    }
}
