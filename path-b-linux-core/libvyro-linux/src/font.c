static const uint8_t BOX[10] = { 0x3E,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x3E };

const uint8_t *vyro_font_glyph(unsigned char c) {
    if (c < 32 || c > 126) return BOX;
    return GLYPHS[c - 32];
}

void vyro_font_blit(uint32_t *pixels, int stride_px, int surf_w, int surf_h,
                    int x, int y, char c, uint32_t color) {
    if (!pixels) return;
    const uint8_t *g = vyro_font_glyph((unsigned char)c);
    for (int row = 0; row < VYRO_FONT_H; row++) {
        int yy = y + row;
        if (yy < 0 || yy >= surf_h) continue;
        uint8_t bits = g[row];
        for (int col = 0; col < VYRO_FONT_W; col++) {
            if (!(bits & (1u << (5 - col)))) continue;
            int xx = x + col;
            if (xx < 0 || xx >= surf_w) continue;
            pixels[yy * stride_px + xx] = color;
        }
    }
}

void vyro_font_text(uint32_t *pixels, int stride_px, int surf_w, int surf_h,
                    int x, int y, const char *s, uint32_t color) {
    if (!s) return;
    int cx = x, cy = y;
    while (*s) {
        if (*s == '\n') { cx = x; cy += VYRO_FONT_H + 2; s++; continue; }
        vyro_font_blit(pixels, stride_px, surf_w, surf_h, cx, cy, *s, color);
        cx += VYRO_FONT_ADVANCE;
        s++;
    }
}
